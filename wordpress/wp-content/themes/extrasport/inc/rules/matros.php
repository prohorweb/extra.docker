<p>1. Настоящие Правила и техника безопасности фитнес-клуба &laquo;Экстра спорт&raquo; (далее &ndash;
Правила) являются обязательными для выполнения всеми членами клуба. В случае отказа Члена Клуба от
ознакомления настоящих Правил и/или от прохождения инструктажа о технике безопасности Член Клуба
самостоятельно несет риски, связанные с нарушениями техники безопасности.</p>
<p>2. Часы работы Клуба устанавливаются с 7.00 до 23.00 (вход в Клуб до 22.00). В праздничные и выходные
дни с 09.00 до 22.00 (Вход в клуб до 21.00). Клуб имеет право изменять часы работы. Информация об
изменениях часов работы размещается на информационных стендах.</p>
<p>3. Пропуском в Клуб является клубная карта, которая оформляется только по предъявлению паспорта и
после подписания договора с Клубом. Член Клуба обязан предъявлять клубную карту при входе в
помещение Клуба. В случае временного отсутствия (замены/утери) клубной карты у Члена Клуба, доступ в
Клуб осуществляется по временному пропуску. В случае отсутствия клубной карты, доступ в Клуб
осуществляется по предъявлению документа, удостоверяющего личность Члена Клуба, до получения Членом
клуба новой карты.</p>
<p>4. Членство в Клубе является персональным и не может быть передано или использовано другими лицами
без переоформления клубной карты. Член Клуба обязан предъявить клубную карту или ключ от шкафа
работникам Клуба по их требованию. Любое лицо, в том числе не являющееся Членом клуба, но
находящееся на его территории обязано соблюдать настоящие правила.</p>
<p>5. Член Клуба имеет право переоформить клубную карту на другое лицо в случае невозможности
самостоятельного посещения Клуба. Для переоформления клубной карты Члену Клуба необходимо письменно
изъявить свое желание, предъявить оригинал договора оказания физкультурно-оздоровительных и
спортивных услуг. С момента переоформления прежняя клубная карта прекращает свое действие. Стоимость
переоформления Клубной карты указана в прайс-листе, размещенном в открытом доступе в отделе продаж и
иных источниках</p>
<p>6. Член Клуба имеет право получить ключ от шкафа в обмен на клубную карту. Использование личных
замков запрещено.</p>
<p>7. В случае утери или порчи клубной карты, ключа от шкафа, порчи любого инвентаря, используемого
Членом Клуба во время занятий, либо имущества Клуба, Член Клуба обязан заплатить возмещение, размер
которого устанавливается Клубом.</p>
<p>8. В период нахождения в Клубе личные вещи Члена Клуба должны храниться в шкафах раздевалки. Клуб не
несет ответственности за личные вещи Членов Клуба.&nbsp;Члены Клуба сдают ценные вещи в персональный
сейф, расположенный на рецепции Клуба, ключ от которого подлежит передаче Члену клуба. После занятия
Член Клуба обязан освободить шкаф/сейф от личных вещей и сдать ключ на рецепцию. Верхнюю одежду Член
клуба обязан сдать в гардероб до входа в зал для тренировок, а также надеть бахилы (если обувь не
является сменной). Клуб не при каких обстоятельствах не несет ответственность за дорогостоящие
личные вещи: драгоценности, часы, деньги и пр.</p>
<p>9. При первом посещении Клуба, Члену Клуба необходимо сфотографироваться в отделе продаж, в противном
случае Клуб имеет право ограничить доступ клиента на территорию Клуба.</p>
<p>10. При первом посещении Клуба Члену Клуба настоятельно рекомендуется пройти фитнес-тестирование и в
дальнейшем строго придерживаться рекомендаций инструкторов и персонала Клуба. Занятия спортом должны
быть регулярные, а физическая нагрузка должна увеличиваться постепенно. Чрезмерная физическая
нагрузка может нанести вред здоровью.</p>
<p>11. Член Клуба обязан осуществлять тренировки в Клубе в спортивной одежде (верхняя часть тела должна
быть закрыта) и сменной спортивной обуви, соблюдать правила общей гигиены, перед посещением
бассейна, сауны принять душ.</p>
<p>12. Клуб имеет право не допускать Члена Клуба на тренировку в обуви и одежде, не предназначенной для
конкретного типа занятий.</p>
<p>13. Член Клуба обязан соблюдать чистоту во всех помещениях Клуба, которые используются им до, во
время и после тренировок.</p>
<p>14. Член Клуба в период нахождения в Клубе обязуется соблюдать правила общественного порядка,
уважительно относится к Членам Клуба и сотрудникам Клуба (вести себя культурно, не использовать в
своей речи ненормативную лексику, не доставлять неудобства посетителям Клуба, не конфликтовать и
т.д.).</p>
<p>15. После окончания тренировок Член Клуба обязан вернуть спортивный инвентарь (грифы, блины, гантели
и т.д.) в специально отведенные места в надлежащем состоянии. За утерю и порчу оборудования,
инвентаря Член Клуба несет материальную ответственность.</p>
<p>16. Для обеспечения безопасности тренировочного процесса в фитнес клубе, Член Клуба обязан выполнять
упражнения с весами, определенными инструктором Клуба. Член Клуба обязуется самостоятельно следить
за своим здоровьем и самочувствием и воздержаться от посещения Клуба в период любого недомогания.
Физические упражнения могут также спровоцировать обострение хронических заболеваний.</p>
<p>17. Групповые занятия в Клубе проводятся по расписаниям, установленным Клубом. Клуб оставляет за
собой право вносить изменения и дополнения в расписание и осуществлять замену заявленного в
расписании инструктора. Член Клуба обязан приходить на групповые занятия без опозданий.</p>
<p>18. Любая тренировка начинается с разминки. Человек психологически и физически готовится к выполнению
упражнений, увеличивается частота сердечных сокращений и приток крови к мышцам. Мышцы становятся
более гибкие и устойчивые к повреждениям. Разминка подготавливает организм к физическим нагрузкам,
предотвращая нежелательные последствия. Нельзя пренебрегать и восстановительной частью или заминкой.
Заминка &mdash; это завершающая часть занятия, которая длится 5-10 минут. Во время заминки пульс
постепенно снижается, организм плавно переходит от интенсивных физических нагрузок к спокойному
состоянию. Восстановительная часть после тренировки значительно снижает вероятность получения
травмы.&nbsp;</p>
<p>19. Основные признаки, при которых надо сразу прекратить тренировку:</p>
<p>- в процессе занятия чувствуется нехватка воздуха;</p>
<p>- появляется отдышка, головокружение и тошнота;</p>
<p>- заметен белый треугольник вокруг рта.</p>
<p>- боль в суставах рук или ног;</p>
<p>- чувствуются мышечные спазмы.</p>
<p>При необходимости вызывать скорую помощь либо обратиться к сотрудникам Клуба для вызова скорой
помощи.</p>
<p>Аптечка первой медицинской помощи находится на рецепции. Лекарственные препараты следует применять
только по назначению врача. За неправильное использование препаратов из аптечки первой медицинской
помощи Клуб ответственности не несет.</p>
<p>20.Перед началом занятия обязательно прочитайте инструкцию на кардиотренажере или тренажере (чаще
всего она размещена прямо на тренажере или около него) или обратитесь за помощью к инструктору.</p>
<p>21.Не оставляйте одежду, полотенца и прочие предметы вблизи кардиотренажера. Ваши вещи могут случайно
попасть в его движущие части, что спровоцирует опасную ситуацию.</p>
<p>22. Не ставьте жидкости вблизи тренажера, а также на полу рядом с ним. Тренажеры подключены к
электричеству, попадание на них воды может вызвать замыкание.</p>
<p>23. Заходить и сходить с тренажера можно только при полной его остановке, соблюдая осторожность.</p>
<p>24. Тренируясь на кардиотренажере, не оборачивайтесь назад. Внимание рассеивается и возрастает риск
получить травму.</p>
<p>25. Во время тренировки нельзя вскрывать части тренажера или наклонять его.</p>
<p>26. Обязательно перед использованием (лучше под руководством инструктора) проверьте исправность
тренажера и надежность его установки и крепления.</p>
<p>27. При выполнении упражнений со штангой надо использовать замки безопасности.</p>
<p>28. Выполнять упражнения с большим весом желательно при страховке инструктора тренажерного зала или
партнера.</p>
<p>29. Запрещается работа на неисправных тренажерах.</p>
<p>30. Упражнения со свободными весами надо выполнять на расстоянии от стекол и зеркал.</p>
<p>31. Запрещается заниматься на кардиотренажере, тренажерном зале, любая физическая активность с
жевательной резинкой во рту;</p>
<p>32. Члену Клуба запрещено входить на территорию Клуба с домашними животными.</p>
<p>33. Члену Клуба, а также приглашенным им и/или сопровождающим его лицам запрещено проносить на
территорию Клуба любое холодное, травматическое, газовое огнестрельное и иные виды оружия.</p>
<p>34. Члену Клуба, а также приглашенным им и/или сопровождающим его лицам запрещено проносить на
территорию Клуба любые легковоспламеняющиеся, взрывоопасные, токсические предметы.</p>
<p>35. Члену Клуба запрещено входить на территорию, предназначенную для служебного пользования.</p>
<p>36. Запрещено проведение персональных тренировок лицами, не являющимися тренерами или инструкторами
Клуба.</p>
<p>37. Члену Клуба запрещено самостоятельно пользоваться музыкальной и другой технической аппаратурой
Клуба либо собственной музыкальной аппаратурой без использования гарнитуры.</p>
<p>38. Осуществлять кино- и фотосъемку в Клубе без письменного разрешения Клуба запрещено.</p>
<p>39. Во время проведения клубных мероприятий Клуб имеет право ограничить зону, предназначенную для
тренировок. Клуб имеет право закрывать помещения на время проведения специальных мероприятий и/или
ремонтных работ, о чем Члены Клуба информируются путем размещения в Клубе объявлений.</p>
<p>40. Все помещения Клуба являются зонами свободными от курения. Членам Клуба запрещено приносить на
территорию Клуба напитки и продукты питания, а также употреблять алкогольные и слабоалкогольные
напитки, включая пиво. Члену Клуба запрещено находиться в Клубе в состоянии алкогольного, в том
числе посталкогольного опьянения, и иного опьянения, принимать пищу в местах, предназначенных для
тренировок, в зонах отдыха и раздевалках.</p>
<p>41. Члену Клуба запрещено размещать объявления, рекламные материалы, проводить опросы и
распространять товары на территории Клуба без письменного разрешения Клуба.</p>
<p>42. Члены клуба несут полную персональную ответственность за детей, а также иных лиц, находящихся на
территории Клуба под их контролем и надзором на территории Клуба. Дети до 14 лет обязаны посещать
Клуб только с персональным тренером Клуба либо с законным представителем. Время персонального
тренера Клуба оплачивается отдельно.</p>
<p>43. При возникновении или угрозе возникновения несчастного случая (травмы, ушибы и т.д.) Член клуба
обязан оповестить о случившимся менеджера отдела продаж, управляющего клубом. О произошедшем
