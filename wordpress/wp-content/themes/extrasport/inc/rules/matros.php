проводится внутреннее расследование. В расследовании должны быть выяснены следующие обстоятельства:
причина возникновения события, вина, виновное лицо, причинно-следственная связь между событием и
последствиями (возможными последствиями), нарушение правил и т.д.&nbsp;</p>
<p>44. Клуб не несет ответственности за вред, причиненный в результате нарушений Членом клуба или
третьим лицами условий договора, настоящих Правил или иных норм.</p>
<p>45. Член Клуба обязан покидать территорию Клуба не позднее установленного времени его закрытия.</p>
<p>46. Договор с Клубом является абонентским договором (ст. 429.4 ГК РФ), в любом случае оплате подлежит
